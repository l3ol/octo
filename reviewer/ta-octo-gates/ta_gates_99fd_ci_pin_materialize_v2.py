#!/usr/bin/env python3
"""TA Reviewer: derive a CI-only GATES 99fd pin from immutable Git objects.

Does not read, upload, alter or reproduce the private Ops pin manifest.
The Ops SHA is a lineage reference, NOT authentication of this runtime pin.
All generated bytes live under approved ephemeral CI scratch. G4 PASS=false.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import subprocess
import sys

TIP = "99fd6a48eca58b88b6730d88875672fb72da9bac"
TREE = "2ba7c96c9c908aedec7f475915f2addb7b70ccf4"
BASE = "5443c9b4dde7fc208a0a72457c87904650829f77"
GATES_TREE = "3e8cc2c58e83e78e91caa9d6370cb9611178d20d"
ARTIFACT_SHA = "42368539d65f50337ea1fbe92e4cf41fba086869aafdb00595fcf0fbb51ed0a8"
CONFIG_SHA = "2feb73d01b2a717b0219253967770ad2da094dd137b918c4a3a35e1dd27ff59a"
CANONICAL_SHA = "cff01a57e38b16af6bc5545789949575b1cbcc3078cdf5bf3158cee4b56fd884"
POLICY_SHA = "68eb1f1844aa24947f9e23a9f21fb1365c50ca85f9012f981c98aed8fbbdfcda"
PROTECTION_SHA = "ab4096de1a460ec7696df488e8d92cf5623b116c190fdf84153bf9037fc0d99e"
RULE_VERSION = "6.0.0"
OPS_ORIGINAL_MANIFEST_SHA = "6250b8d339dc5278c4aaf2a00577144ff5ce11c9500d7b5f0b3e185984a29763"
OPS_RO_TRANSCRIPT_SHA = "fa8622b01827a186b7fd54860320dc3bd9eaf63d3df9b132431893a76afa43d9"
OPS_PACKAGE_SUMS_SHA = "9b1e7806170e4c45dd68e783ffc5d7d78325f25125a3330669d587127f092894"

def digest(raw: bytes) -> str:
    return hashlib.sha256(raw).hexdigest()

def run(*args: str, cwd: Path | None = None) -> bytes:
    p = subprocess.run(args, cwd=cwd, capture_output=True, check=False, timeout=45)
    if p.returncode:
        raise RuntimeError(f"read-only command failed: {args[0]} rc={p.returncode}")
    return p.stdout

def git(repo: Path, *args: str) -> str:
    return run("git", "-C", str(repo), *args).decode("utf-8").strip()

def assert_inside(target: Path, parent: Path) -> None:
    if not target.is_relative_to(parent) or target == parent:
        raise ValueError("output must be inside the declared disposable runner scratch")

def main() -> int:
    p = argparse.ArgumentParser()
    p.add_argument("--candidate", type=Path, required=True)
    p.add_argument("--runner-temp", type=Path, required=True)
    p.add_argument("--pin-base", type=Path, required=True)
    p.add_argument("--receipt", type=Path, required=True)
    args = p.parse_args()
    repo = args.candidate.resolve(strict=True)
    runner_temp = args.runner_temp.resolve(strict=True)
    pin_base = args.pin_base.resolve()
    receipt = args.receipt.resolve()
    assert_inside(pin_base, runner_temp)
    assert_inside(receipt, runner_temp)
    if pin_base.exists() or receipt.exists():
        raise FileExistsError("fail closed: CI pin or lineage destination already exists")
    if repo == runner_temp or repo.is_relative_to(runner_temp) or runner_temp.is_relative_to(repo):
        raise ValueError("candidate and ephemeral runner scratch must be separate")
    if git(repo, "rev-parse", "HEAD") != TIP:
        raise ValueError("candidate head drift")
    if git(repo, "rev-parse", "HEAD^{tree}") != TREE:
        raise ValueError("candidate tree drift")
    if git(repo, "cat-file", "-t", BASE) != "commit":
        raise ValueError("base object missing")
    run("git", "-C", str(repo), "merge-base", "--is-ancestor", BASE, TIP)
    if git(repo, "status", "--porcelain=v1", "--untracked-files=all") != "":
        raise ValueError("candidate is dirty")
    if git(repo, "cat-file", "-t", TIP) != "commit":
        raise ValueError("pin object is not a commit")
    if git(repo, "rev-parse", f"{TIP}:gates") != GATES_TREE:
        raise ValueError("protected gate tree drift")
    archived = run("git", "-C", str(repo), "archive", "--format=tar", TIP)
    if digest(archived) != ARTIFACT_SHA:
        raise ValueError("frozen artifact digest mismatch")
    sys.path.insert(0, str(repo))
    from gates.config_inventory import evaluate_pinned_config
    from gates.isolation_bed import materialize_pin_manifest
    fresh = evaluate_pinned_config(repo, TIP)
    if fresh["config_digest"] != CONFIG_SHA:
        raise ValueError("frozen config digest mismatch")
    fields = fresh["config_manifest"]
    expected = {
        "parameters_canonical_sha256": CANONICAL_SHA,
        "policy_config_digest": POLICY_SHA,
        "protection_settings_digest": PROTECTION_SHA,
        "rule_version": RULE_VERSION,
    }
    if fields != expected:
        raise ValueError("config components or rule version mismatch")

    # A new runtime manifest is issued for CI scratch, NOT a rewritten Ops manifest.
    manifest_path = pin_base / "manifests" / "pin99fd-ci.json"
    extract_root = pin_base / "pins" / TIP
    manifest = materialize_pin_manifest(
        repo,
        TIP,
        manifest_path=manifest_path,
        extract_root=extract_root,
        candidate_worktree=repo,
        build_candidate_sha=TIP,
    )
    materialized = json.loads(manifest_path.read_bytes())
    if materialized != manifest:
        raise ValueError("serialized generated manifest mismatch")
    checks = {
        "gates_pin_sha": TIP,
        "runtime_gates_pin_sha": TIP,
        "build_candidate_sha": TIP,
        "source_commit": TIP,
        "gate_tree_sha": GATES_TREE,
        "pin_tree_sha": TREE,
        "artifact_digest": ARTIFACT_SHA,
        "config_digest": CONFIG_SHA,
        "rule_version": RULE_VERSION,
        **expected,
    }
    for name, wanted in checks.items():
        if materialized.get(name) != wanted:
            raise ValueError("generated manifest field mismatch: " + name)
    if materialized["git_repo"] != str(repo) or materialized["extract_root"] != str(extract_root):
        raise ValueError("runtime paths do not point to actual CI scratch and repo")
    manifest_sha = digest(manifest_path.read_bytes())
    if manifest_sha == OPS_ORIGINAL_MANIFEST_SHA:
        raise ValueError("derived CI manifest must not impersonate exact Ops bytes")
    if not (pin_base / "pins" / TIP / "gates" / "tamper" / "loader.py").is_file():
        raise ValueError("protected gate sources missing from extracted snapshot")
    if git(repo, "status", "--porcelain=v1", "--untracked-files=all") != "":
        raise ValueError("candidate changed during CI derivation")

    lineage = {
        "kind": "TA_CI_99FD_DERIVED_PIN_LINEAGE_V1",
        "authority_class": "CI_DISPOSABLE_TEST_PIN_NOT_OPS_PRODUCTION_AUTHORITY",
        "candidate_commit": TIP,
        "candidate_tree": TREE,
        "base_commit": BASE,
        "gate_tree": GATES_TREE,
        "pin_commit": TIP,
        "source_git_archive_sha256": ARTIFACT_SHA,
        "source_config_digest": CONFIG_SHA,
        "ci_runtime_manifest_sha256": manifest_sha,
        "ci_runtime_manifest": str(manifest_path),
        "ci_pinned_code_root": str(extract_root),
        "derivation_method": "fixed-99fd-git-object-to-existing-gates.isolation_bed.materialize_pin_manifest",
        "ops_original_manifest_sha256_reference_only": OPS_ORIGINAL_MANIFEST_SHA,
        "ops_original_readonly_transcript_sha256_reference_only": OPS_RO_TRANSCRIPT_SHA,
        "ops_package_sha256s_sha256_reference_only": OPS_PACKAGE_SUMS_SHA,
        "ops_original_manifest_bytes_imported": False,
        "ops_private_host_paths_imported": False,
        "runtime_pin_requires_independent_mount_readonly_proof": True,
        "g4_pass": False,
        "runtime_pass": False,
    }
    receipt.parent.mkdir(parents=True, exist_ok=True)
    receipt.write_text(json.dumps(lineage, ensure_ascii=False, sort_keys=True, indent=2) + "\n")
    print(json.dumps({
        "status": "DERIVED_CI_PIN_READY_NOT_G4",
        "pin_manifest_sha256": manifest_sha,
        "lineage_receipt_sha256": digest(receipt.read_bytes()),
        "gate_artifact_sha256": ARTIFACT_SHA,
        "gate_config_sha256": CONFIG_SHA,
        "ops_original_manifest_sha256_reference_only": OPS_ORIGINAL_MANIFEST_SHA,
        "runtime_pass": False,
    }, sort_keys=True))
    return 0

if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except (OSError, RuntimeError, ValueError) as exc:
        print("CI_PIN_DERIVATION_BLOCKED " + type(exc).__name__ + ": " + str(exc), file=sys.stderr)
        raise SystemExit(2)
